/**
 * @defgroup subsys_canopen CANopen
 * @ingroup subsys
 * @brief CANopen device (CiA 301) on a CAN controller.
 *
 * A node runs the NMT slave, heartbeat producer and consumers, SDO server, PDOs, SYNC consumer and
 * EMCY producer of one device on the bus. Its object dictionary is generated from a YAML file by
 * pbl_canopen_od() in the application's CMakeLists.txt, which declares the dictionary in a header
 * of the same name:
 *
 * @code{.c}
 * #include "od.h"
 *
 * static struct pbl_canopen s_co;
 *
 * const struct pbl_canopen_config cfg = {
 *   .can = CAN_BUS,
 *   .od = &od,
 *   .node_id = 5,
 *   .bitrate = 500000,
 * };
 *
 * ret = pbl_canopen_init(&s_co, &cfg);
 * ret = pbl_canopen_start(&s_co);
 * ret = pbl_canopen_od_write(&s_co, OD_STATUS, 0, &status, sizeof(status));
 * @endcode
 *
 * The node runs on a thread of its own, which also calls the callbacks. Calls return 0 or a
 * negative errno.
 * @{
 */

/** @brief Data types of object dictionary entries. */
enum pbl_canopen_type {
  PBL_CANOPEN_TYPE_BOOLEAN = 0x01,
  PBL_CANOPEN_TYPE_INTEGER8 = 0x02,
  PBL_CANOPEN_TYPE_INTEGER16 = 0x03,
  PBL_CANOPEN_TYPE_INTEGER32 = 0x04,
  PBL_CANOPEN_TYPE_UNSIGNED8 = 0x05,
  PBL_CANOPEN_TYPE_UNSIGNED16 = 0x06,
  PBL_CANOPEN_TYPE_UNSIGNED32 = 0x07,
  PBL_CANOPEN_TYPE_REAL32 = 0x08,
  PBL_CANOPEN_TYPE_VISIBLE_STRING = 0x09,
  PBL_CANOPEN_TYPE_OCTET_STRING = 0x0a,
  PBL_CANOPEN_TYPE_REAL64 = 0x11,
  PBL_CANOPEN_TYPE_INTEGER64 = 0x15,
  PBL_CANOPEN_TYPE_UNSIGNED64 = 0x1b,
};

/**
 * @name Entry attributes
 * @{
 */
/** Readable over the bus. */
#define PBL_CANOPEN_ATTR_READ PBL_BIT(0)
/** Writable over the bus. */
#define PBL_CANOPEN_ATTR_WRITE PBL_BIT(1)
/** Mappable to a TPDO. */
#define PBL_CANOPEN_ATTR_TPDO PBL_BIT(2)
/** Mappable to an RPDO. */
#define PBL_CANOPEN_ATTR_RPDO PBL_BIT(3)
/** Default value plus the node-ID. */
#define PBL_CANOPEN_ATTR_NODEID PBL_BIT(4)
/** @} */

/** @brief NMT states, with their heartbeat codes. */
enum pbl_canopen_nmt_state {
  PBL_CANOPEN_NMT_INITIALIZING = 0x00,
  PBL_CANOPEN_NMT_STOPPED = 0x04,
  PBL_CANOPEN_NMT_OPERATIONAL = 0x05,
  PBL_CANOPEN_NMT_PRE_OPERATIONAL = 0x7f,
};

/** @brief Resets, as requested by the NMT master. */
enum pbl_canopen_reset {
  /** Communication parameters back to their defaults. */
  PBL_CANOPEN_RESET_COMM,
  /** Communication and application parameters back to their defaults. */
  PBL_CANOPEN_RESET_NODE,
};

/** @brief Heartbeat consumer events. */
enum pbl_canopen_hb_event {
  /** A monitored node sent its boot-up message. */
  PBL_CANOPEN_HB_BOOT,
  /** A monitored node changed state. */
  PBL_CANOPEN_HB_STATE,
  /** A monitored node missed its heartbeat. */
  PBL_CANOPEN_HB_TIMEOUT,
};

/** @brief An object dictionary entry: one sub-index of an object. */
struct pbl_canopen_od_entry {
  /** Index. */
  uint16_t index;
  /** Sub-index. */
  uint8_t subindex;
  /** Data type, @ref pbl_canopen_type. */
  uint8_t type;
  /** Attributes, @c PBL_CANOPEN_ATTR_* flags. */
  uint8_t attr;
  /** Size of the value in bytes, the largest one for strings. */
  uint16_t size;
  /** Value, in the CPU's byte order. */
  void *data;
};

struct pbl_canopen;

/** @cond INTERNAL_HIDDEN */
#define PBL_CANOPEN_PDO_MAX_MAP 8U

struct pbl_canopen__pdo {
  struct pbl_canopen *co;
  struct pbl_delayed_work timer;
  const struct pbl_canopen_od_entry *map[PBL_CANOPEN_PDO_MAX_MAP];
  uint8_t map_len[PBL_CANOPEN_PDO_MAX_MAP];
  uint32_t can_id;
  uint16_t num;
  uint8_t num_map;
  uint8_t len;
  uint8_t type;
  bool valid;
  bool ext;
};

struct pbl_canopen__tpdo {
  struct pbl_canopen__pdo pdo;
  struct pbl_delayed_work inhibit;
  uint8_t sync_count;
  bool sync_started;
  bool event;
  bool inhibited;
};

struct pbl_canopen__rpdo {
  struct pbl_canopen__pdo pdo;
  uint8_t buf[PBL_CAN_MAX_LEN];
  bool buffered;
  bool monitored;
};

struct pbl_canopen__hb_consumer {
  struct pbl_canopen *co;
  struct pbl_delayed_work timeout;
  uint16_t time_ms;
  uint8_t node_id;
  uint8_t state;
  bool alive;
};
/** @endcond */

/**
 * @brief An object dictionary, generated by pbl_canopen_od().
 *
 * Its values live in two areas, communication (0x1000-0x1fff) and application (0x2000-0xffff),
 * each restored from its defaults on the matching reset.
 */
struct pbl_canopen_od {
  /** Entries, sorted by index and sub-index. */
  const struct pbl_canopen_od_entry *entries;
  /** Number of entries. */
  uint16_t num_entries;
  /** Communication area values. */
  void *comm;
  /** Communication area defaults. */
  const void *comm_defaults;
  /** Communication area size in bytes. */
  size_t comm_size;
  /** Application area values. */
  void *app;
  /** Application area defaults. */
  const void *app_defaults;
  /** Application area size in bytes. */
  size_t app_size;
  /** Buffer for SDO transfers, as large as the largest entry. */
  uint8_t *buf;
  /** Size of @ref buf in bytes. */
  size_t buf_size;
  /** RPDOs. */
  struct pbl_canopen__rpdo *rpdos;
  /** TPDOs. */
  struct pbl_canopen__tpdo *tpdos;
  /** Heartbeat consumers. */
  struct pbl_canopen__hb_consumer *hb_consumers;
  /** Number of RPDOs. */
  uint16_t num_rpdos;
  /** Number of TPDOs. */
  uint16_t num_tpdos;
  /** Number of heartbeat consumers, entries of object 0x1016. */
  uint8_t num_hb_consumers;
  /** Depth of the error history, object 0x1003, 0 without it. */
  uint8_t num_errors;
};

/** @brief Node callbacks, all called from the node's thread. */
struct pbl_canopen_callbacks {
  /**
   * NMT state changed.
   *
   * @param co Node.
   * @param state New state.
   * @param arg Callback argument.
   */
  void (*nmt)(struct pbl_canopen *co, enum pbl_canopen_nmt_state state, void *arg);
  /**
   * Reset requested by the NMT master, called once the defaults are restored and before the
   * boot-up message, to set the values that differ from them.
   *
   * @param co Node.
   * @param reset Reset.
   * @param arg Callback argument.
   */
  void (*reset)(struct pbl_canopen *co, enum pbl_canopen_reset reset, void *arg);
  /**
   * An application entry is about to be written over the bus, by an SDO or an RPDO.
   *
   * @param co Node.
   * @param index Index.
   * @param subindex Sub-index.
   * @param data New value, in the CPU's byte order.
   * @param len Size of the new value in bytes.
   * @param arg Callback argument.
   * @return 0 to store the value, @c -EINVAL or @c -ERANGE to refuse it as invalid, @c -EBUSY to
   * refuse it in the present state, or another negative errno to refuse it otherwise.
   */
  int (*write)(struct pbl_canopen *co, uint16_t index, uint8_t subindex, const void *data,
               size_t len, void *arg);
  /**
   * SYNC received in operational state, after the synchronous RPDOs are applied and before the
   * synchronous TPDOs are sampled: where the application takes its new values and reports its
   * own. It holds up the node's thread while it runs.
   *
   * @param co Node.
   * @param counter SYNC counter, 0 without one.
   * @param cycles Value of pbl_cycle_get_32() when the controller handed the SYNC over, to
   * measure how late the callback runs.
   * @param arg Callback argument.
   */
  void (*sync)(struct pbl_canopen *co, uint8_t counter, uint32_t cycles, void *arg);
  /**
   * Heartbeat consumer event.
   *
   * @param co Node.
   * @param node_id Monitored node.
   * @param event Event.
   * @param state The node's last state.
   * @param arg Callback argument.
   */
  void (*heartbeat)(struct pbl_canopen *co, uint8_t node_id, enum pbl_canopen_hb_event event,
                    enum pbl_canopen_nmt_state state, void *arg);
};

/** @brief Node configuration. */
struct pbl_canopen_config {
  /** CAN controller, configured and started by the node. */
  const struct pbl_can *can;
  /** Object dictionary, used by this node only. */
  const struct pbl_canopen_od *od;
  /** Node-ID, 1 to 127. */
  uint8_t node_id;
  /** Bit rate, in bits per second. */
  uint32_t bitrate;
  /** Callbacks, or NULL. */
  const struct pbl_canopen_callbacks *cb;
  /** Callback argument. */
  void *arg;
};

/** @cond INTERNAL_HIDDEN */
struct pbl_canopen__frame {
  uint32_t id;
  uint32_t cycles;
  uint8_t len;
  uint8_t flags;
  uint8_t data[PBL_CAN_MAX_LEN];
};

struct pbl_canopen__emcy {
  uint16_t code;
  uint8_t reg;
  uint8_t msef[5];
};

struct pbl_canopen__sdo {
  struct pbl_delayed_work timeout;
  const struct pbl_canopen_od_entry *entry;
  uint32_t size;
  uint32_t offset;
  uint8_t state;
  bool toggle;
};

struct pbl_canopen {
  struct pbl_mutex lock;
  struct pbl_canopen_config cfg;
  struct pbl_msgq rxq;
  struct pbl_canopen__frame rx_buf[CONFIG_CANOPEN_RX_QUEUE_SIZE];
  struct pbl_work rx_work;
  struct pbl_canopen__frame tx_buf[CONFIG_CANOPEN_TX_QUEUE_SIZE];
  uint8_t tx_head;
  uint8_t tx_count;
  struct pbl_work tx_work;
  struct pbl_delayed_work heartbeat;
  struct pbl_canopen__sdo sdo;
  struct pbl_canopen__emcy emcy_active[CONFIG_CANOPEN_EMCY_ACTIVE];
  uint8_t num_emcy_active;
  struct pbl_canopen__emcy emcy_queue[CONFIG_CANOPEN_EMCY_QUEUE];
  uint8_t emcy_head;
  uint8_t emcy_count;
  struct pbl_delayed_work emcy_inhibit;
  bool emcy_inhibited;
  struct pbl_work can_work;
  enum pbl_can_bus_state bus_state;
  enum pbl_canopen_nmt_state nmt;
  struct pbl_delayed_work sync_timeout;
  uint64_t sync_ticks;
  uint32_t sync_cycles;
  bool sync_seen;
  uint32_t rx_overruns;
  uint32_t tx_overruns;
  bool rx_overrun;
  bool started;
};
/** @endcond */

/**
 * @brief Initialize a node, stopped.
 *
 * @param co Node.
 * @param cfg Configuration, copied.
 * @return 0, @c -EINVAL for an invalid configuration, or another negative errno.
 */
int pbl_canopen_init(struct pbl_canopen *co, const struct pbl_canopen_config *cfg);

/**
 * @brief Start the node: join the bus, restore every default and go pre-operational.
 *
 * @param co Node.
 * @return 0, @c -EALREADY if started, or a negative errno from the CAN controller.
 */
int pbl_canopen_start(struct pbl_canopen *co);

/**
 * @brief Stop the node and leave the bus.
 *
 * @param co Node.
 * @return 0 or a negative errno from the CAN controller.
 */
int pbl_canopen_stop(struct pbl_canopen *co);

/**
 * @brief Get the NMT state.
 *
 * @param co Node.
 * @return NMT state, @ref PBL_CANOPEN_NMT_INITIALIZING while stopped.
 */
enum pbl_canopen_nmt_state pbl_canopen_nmt_state(struct pbl_canopen *co);

/**
 * @brief Read an entry of the object dictionary.
 *
 * @param co Node.
 * @param index Index.
 * @param subindex Sub-index.
 * @param[out] data Value, in the CPU's byte order.
 * @param len Size of @p data in bytes.
 * @return Size of the value in bytes, @c -ENOENT if there is no such entry, or @c -ENOSPC if
 * @p data is too small for it.
 */
int pbl_canopen_od_read(struct pbl_canopen *co, uint16_t index, uint8_t subindex, void *data,
                        size_t len);

/**
 * @brief Write an entry of the object dictionary, whatever its access over the bus.
 *
 * A value that changes triggers the event-driven TPDOs that map the entry.
 *
 * @param co Node.
 * @param index Index.
 * @param subindex Sub-index.
 * @param data Value, in the CPU's byte order.
 * @param len Size of the value in bytes: the entry's size, or up to it for strings.
 * @return 0, @c -ENOENT if there is no such entry, or @c -EINVAL for a wrong size.
 */
int pbl_canopen_od_write(struct pbl_canopen *co, uint16_t index, uint8_t subindex, const void *data,
                         size_t len);

/**
 * @brief Request the transmission of a TPDO.
 *
 * An event-driven TPDO goes as soon as its inhibit time allows, an acyclic synchronous one on the
 * next SYNC.
 *
 * @param co Node.
 * @param num TPDO number, from 1.
 * @return 0, @c -ENOENT if there is no such TPDO, or @c -ENOTSUP for a cyclic one.
 */
int pbl_canopen_tpdo_request(struct pbl_canopen *co, uint16_t num);

/**
 * @brief Raise an error: set its error register bits, add it to the error history and send an
 * emergency message.
 *
 * @param co Node.
 * @param code Emergency error code.
 * @param reg Error register bits, besides the generic error bit.
 * @param msef Manufacturer-specific error field, 5 bytes, or NULL.
 * @return 0, @c -EALREADY if the error is raised, or @c -ENOSPC if too many errors are.
 */
int pbl_canopen_emcy_raise(struct pbl_canopen *co, uint16_t code, uint8_t reg, const uint8_t *msef);

/**
 * @brief Clear an error raised by pbl_canopen_emcy_raise(), and send an error reset message.
 *
 * @param co Node.
 * @param code Emergency error code.
 * @return 0, or @c -ENOENT if the error is not raised.
 */
int pbl_canopen_emcy_clear(struct pbl_canopen *co, uint16_t code);

/** @} */
