#pragma once

#include <pbl/util/bits.h>

#define GH3026_CMD_ADDR   0xDDDDU
#define GH3026_CMD_RESET  0xC2U
#define GH3026_CMD_WAKEUP 0xC3U
#define GH3026_CMD_SLEEP  0xC4U
#define GH3026_FIFO_ADDR  0xAAAAU

#define GH3026_CTRL            0x0000U
#define GH3026_CTRL_SAMPLE_EN  PBL_BIT(0)
#define GH3026_SAMPLE_RATE     0x0004U
#define GH3026_SAMPLE_RATE_DIV PBL_GENMASK(7, 0)
#define GH3026_FIFO_WATERMARK  0x000AU
#define GH3026_PRODUCT_ID_L    0x0030U
#define GH3026_PRODUCT_ID_H    0x0032U
#define GH3026_CHIP_ID         0x0034U
#define GH3026_READY           0x0036U
#define GH3026_READY_CODE      0xAA55U

#define GH3026_SLOT_SEQ(n)   (0x0100U + 2U * ((n) / 2U))
#define GH3026_SLOT_SEQ_EVEN PBL_GENMASK(3, 0)
#define GH3026_SLOT_SEQ_ODD  PBL_GENMASK(11, 8)
#define GH3026_SLOT_SEQ_END  8U
#define GH3026_SLOT_EN       0x0108U

#define GH3026_SLOT_BASE            0x010AU
#define GH3026_SLOT_STRIDE          0x1CU
#define GH3026_SLOT_REG(slot, off)  (GH3026_SLOT_BASE + (slot) * GH3026_SLOT_STRIDE + (off))
#define GH3026_SLOT_CTRL0           0x00U
#define GH3026_SLOT_CTRL0_RX_EN(rx) PBL_BIT(2U + (rx))
#define GH3026_SLOT_CTRL0_RX_EN_ALL PBL_GENMASK(5, 2)
#define GH3026_SLOT_CTRL0_FIFO_EN   PBL_BIT(6)
#define GH3026_SLOT_CTRL0_SR_MULT   PBL_GENMASK(15, 8)
#define GH3026_SLOT_CTRL4           0x08U
#define GH3026_SLOT_CTRL4_GAIN(rx)  PBL_GENMASK(4U * (rx) + 3U, 4U * (rx))
#define GH3026_SLOT_CTRL10          0x14U
#define GH3026_SLOT_CTRL_DRV_CODE   PBL_GENMASK(7, 0)

#define GH3026_SLOT_TIMER(pos) (0x01ECU + 2U * (pos))

#define GH3026_INT_STATUS         0x0508U
#define GH3026_INT_FIFO_USED      0x050AU
#define GH3026_INT_ALL            PBL_GENMASK(14, 0)
#define GH3026_INT_FIFO_WATERMARK PBL_BIT(5)
#define GH3026_INT_FIFO_FULL      PBL_BIT(6)
#define GH3026_INT_CHIP_RESET     PBL_BIT(14)

#define GH3026_LED_FS          0x0692U
#define GH3026_LED_FS_DRV(led) PBL_GENMASK(4U * (led) + 1U, 4U * (led))

#define GH3026_EFUSE_CTRL        0x0700U
#define GH3026_EFUSE_CTRL_ENABLE 0x0020U
#define GH3026_EFUSE_CTRL_READ0  0x0030U
#define GH3026_EFUSE_RDATA1      0x0712U
#define GH3026_EFUSE_RDATA_LED   PBL_GENMASK(7, 0)
#define GH3026_EFUSE_STATUS      0x0718U
#define GH3026_EFUSE_STATUS_DONE PBL_BIT(0)

#define GH3026_FIFO_SLOT PBL_GENMASK(31, 29)
#define GH3026_FIFO_RX   PBL_GENMASK(28, 27)
#define GH3026_FIFO_ADJ  PBL_GENMASK(26, 25)
#define GH3026_FIFO_DATA PBL_GENMASK(23, 0)
#define GH3026_FIFO_ZERO 0x800000
