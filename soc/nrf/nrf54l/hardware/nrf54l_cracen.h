#pragma once

#include <stdint.h>

#include <pbl/util/bits.h>

/* Wrapper register offsets */

#define NRF54L_CRACEN_ENABLE_OFFSET 0x0400

/* Core register offsets */

#define NRF54L_CRACEN_DMA_FETCHADDRLSB_OFFSET 0x0000
#define NRF54L_CRACEN_DMA_PUSHADDRLSB_OFFSET  0x0010
#define NRF54L_CRACEN_DMA_INTSTATRAW_OFFSET   0x0028
#define NRF54L_CRACEN_DMA_INTSTATCLR_OFFSET   0x0030
#define NRF54L_CRACEN_DMA_CONFIG_OFFSET       0x0034
#define NRF54L_CRACEN_DMA_START_OFFSET        0x0038
#define NRF54L_CRACEN_DMA_STATUS_OFFSET       0x003c

#define NRF54L_CRACEN_RNG_CONTROL_OFFSET     0x1000
#define NRF54L_CRACEN_RNG_FIFOLEVEL_OFFSET   0x1004
#define NRF54L_CRACEN_RNG_KEY_OFFSET(n)      (0x1010 + 4 * (n))
#define NRF54L_CRACEN_RNG_STATUS_OFFSET      0x1030
#define NRF54L_CRACEN_RNG_INITWAITVAL_OFFSET 0x1034
#define NRF54L_CRACEN_RNG_SWOFFTMRVAL_OFFSET 0x1040
#define NRF54L_CRACEN_RNG_CLKDIV_OFFSET      0x1044
#define NRF54L_CRACEN_RNG_FIFO_OFFSET        0x1080

/* Wrapper register bit definitions */

#define CRACEN_ENABLE_CRYPTOMASTER PBL_BIT(0)
#define CRACEN_ENABLE_RNG          PBL_BIT(1)
#define CRACEN_ENABLE_PKEIKG       PBL_BIT(2)

/* Core register bit definitions */

#define CRACEN_DMA_INT_FETCH_ERROR PBL_BIT(2)
#define CRACEN_DMA_INT_PUSH_ERROR  PBL_BIT(5)

#define CRACEN_DMA_CONFIG_FETCHCTRLINDIRECT PBL_BIT(0)
#define CRACEN_DMA_CONFIG_PUSHCTRLINDIRECT  PBL_BIT(1)
#define CRACEN_DMA_CONFIG_SOFTRST           PBL_BIT(4)

#define CRACEN_DMA_START_FETCH PBL_BIT(0)
#define CRACEN_DMA_START_PUSH  PBL_BIT(1)

#define CRACEN_DMA_STATUS_FETCHBUSY       PBL_BIT(0)
#define CRACEN_DMA_STATUS_PUSHBUSY        PBL_BIT(1)
#define CRACEN_DMA_STATUS_PUSHWAITINGFIFO PBL_BIT(5)
#define CRACEN_DMA_STATUS_SOFTRSTBUSY     PBL_BIT(6)

#define CRACEN_RNG_CONTROL_ENABLE              PBL_BIT(0)
#define CRACEN_RNG_CONTROL_SOFTRST             PBL_BIT(8)
#define CRACEN_RNG_CONTROL_NB128BITBLOCKS_MASK PBL_GENMASK(19, 16)

#define CRACEN_RNG_STATUS_STATE_MASK  PBL_GENMASK(3, 1)
#define CRACEN_RNG_STATUS_STATE_RESET 0x0U
#define CRACEN_RNG_STATUS_STATE_ERROR 0x5U

/* Scatter-gather DMA descriptor */

struct nrf54l_cracen_dma_desc {
  const void *addr;
  const struct nrf54l_cracen_dma_desc *next;
  uint32_t len;
  uint32_t tag;
};

#define CRACEN_DMA_DESC_STOP ((const struct nrf54l_cracen_dma_desc *)1)

#define CRACEN_DMA_LEN_REALIGN PBL_BIT(29)

#define CRACEN_DMA_TAG_ENGINE_AES  0x1U
#define CRACEN_DMA_TAG_ENGINE_HASH 0x3U
#define CRACEN_DMA_TAG_CONFIG      PBL_BIT(4)
#define CRACEN_DMA_TAG_LAST        PBL_BIT(5)
#define CRACEN_DMA_TAG_DATATYPE(x) PBL_FIELD_PREP(PBL_GENMASK(7, 6), (x))
#define CRACEN_DMA_TAG_OFFSET(x)   PBL_FIELD_PREP(PBL_GENMASK(15, 8), (x))

/* AES engine */

#define CRACEN_AES_REG_CONFIG 0x00U
#define CRACEN_AES_REG_KEY    0x08U

#define CRACEN_AES_CONFIG_DECRYPT  PBL_BIT(0)
#define CRACEN_AES_CONFIG_MODE_ECB PBL_FIELD_PREP(PBL_GENMASK(16, 8), 0x001U)

/* Hash engine */

#define CRACEN_HASH_DATATYPE_MESSAGE 0U
#define CRACEN_HASH_DATATYPE_STATE   1U

#define CRACEN_HASH_CONFIG_SHA256 0x08U
