#pragma once

#include <pbl/util/bits.h>

/* Register offsets, the C1 ones being those of the Cortex-M7, the C2 ones those of the Cortex-M4 */

#define STM32H7_EXTI_RTSR1_OFFSET  0x0000
#define STM32H7_EXTI_FTSR1_OFFSET  0x0004
#define STM32H7_EXTI_C1IMR1_OFFSET 0x0080
#define STM32H7_EXTI_C1EMR1_OFFSET 0x0084
#define STM32H7_EXTI_C1PR1_OFFSET  0x0088
#define STM32H7_EXTI_C1IMR2_OFFSET 0x0090
#define STM32H7_EXTI_C1EMR2_OFFSET 0x0094
#define STM32H7_EXTI_C1PR2_OFFSET  0x0098
#define STM32H7_EXTI_C1IMR3_OFFSET 0x00a0
#define STM32H7_EXTI_C1EMR3_OFFSET 0x00a4
#define STM32H7_EXTI_C1PR3_OFFSET  0x00a8
#define STM32H7_EXTI_C2IMR1_OFFSET 0x00c0
#define STM32H7_EXTI_C2EMR1_OFFSET 0x00c4
#define STM32H7_EXTI_C2PR1_OFFSET  0x00c8
#define STM32H7_EXTI_C2IMR2_OFFSET 0x00d0
#define STM32H7_EXTI_C2EMR2_OFFSET 0x00d4
#define STM32H7_EXTI_C2PR2_OFFSET  0x00d8
#define STM32H7_EXTI_C2IMR3_OFFSET 0x00e0
#define STM32H7_EXTI_C2EMR3_OFFSET 0x00e4
#define STM32H7_EXTI_C2PR3_OFFSET  0x00e8

/* Those of the core running the code, each set 0x40 past the Cortex-M7's on the Cortex-M4 */
#ifdef CONFIG_CPU_CORTEX_M4
#define STM32H7_EXTI_CORE_OFFSET 0x0040
#else
#define STM32H7_EXTI_CORE_OFFSET 0x0000
#endif
#define STM32H7_EXTI_CORE_IMR1_OFFSET (STM32H7_EXTI_C1IMR1_OFFSET + STM32H7_EXTI_CORE_OFFSET)
#define STM32H7_EXTI_CORE_EMR1_OFFSET (STM32H7_EXTI_C1EMR1_OFFSET + STM32H7_EXTI_CORE_OFFSET)
#define STM32H7_EXTI_CORE_PR1_OFFSET  (STM32H7_EXTI_C1PR1_OFFSET + STM32H7_EXTI_CORE_OFFSET)
#define STM32H7_EXTI_CORE_IMR2_OFFSET (STM32H7_EXTI_C1IMR2_OFFSET + STM32H7_EXTI_CORE_OFFSET)
#define STM32H7_EXTI_CORE_EMR2_OFFSET (STM32H7_EXTI_C1EMR2_OFFSET + STM32H7_EXTI_CORE_OFFSET)
#define STM32H7_EXTI_CORE_PR2_OFFSET  (STM32H7_EXTI_C1PR2_OFFSET + STM32H7_EXTI_CORE_OFFSET)
#define STM32H7_EXTI_CORE_IMR3_OFFSET (STM32H7_EXTI_C1IMR3_OFFSET + STM32H7_EXTI_CORE_OFFSET)
#define STM32H7_EXTI_CORE_EMR3_OFFSET (STM32H7_EXTI_C1EMR3_OFFSET + STM32H7_EXTI_CORE_OFFSET)
#define STM32H7_EXTI_CORE_PR3_OFFSET  (STM32H7_EXTI_C1PR3_OFFSET + STM32H7_EXTI_CORE_OFFSET)

/* The first interrupt mask register of the other core */
#define STM32H7_EXTI_OTHER_IMR1_OFFSET \
  (STM32H7_EXTI_C1IMR1_OFFSET + (0x0040 - STM32H7_EXTI_CORE_OFFSET))

/* The interrupt mask register of a line, of the core running the code */
#define STM32H7_EXTI_CORE_IMR_OFFSET(line) (STM32H7_EXTI_CORE_IMR1_OFFSET + ((line) / 32U) * 0x10U)

/* The NVIC interrupt of the lines a device interrupts through */
#define STM32H7_EXTI_IRQ(line)  STM32H7_EXTI_IRQ_(line)
#define STM32H7_EXTI_IRQ_(line) STM32H7_EXTI_LINE##line##_IRQ
#define STM32H7_EXTI_LINE17_IRQ 41
#define STM32H7_EXTI_LINE47_IRQ 93
#define STM32H7_EXTI_LINE48_IRQ 138
#define STM32H7_EXTI_LINE77_IRQ 125
#define STM32H7_EXTI_LINE78_IRQ 126

/* Lines 55 to 60, of the PWR wakeup pins, in the second set of registers */
#define EXTI_LINES2_WKUP PBL_GENMASK(28, 23)

/* Line 80, of the SEV of the Cortex-M7, in the third set */
#define EXTI_LINES3_CM7_SEV PBL_BIT(16)

/* SYSCFG register offsets */

#define STM32H7_SYSCFG_EXTICR_OFFSET(line) (0x0008 + ((line) / 4U) * 4U)

#define SYSCFG_EXTICR_MASK(line) (0xfU << (((line) % 4U) * 4U))
