#pragma once

#include <pbl/util/bits.h>

/* Register offsets */

#define STM32H7_QUADSPI_CR_OFFSET  0x0000
#define STM32H7_QUADSPI_DCR_OFFSET 0x0004
#define STM32H7_QUADSPI_SR_OFFSET  0x0008
#define STM32H7_QUADSPI_FCR_OFFSET 0x000c
#define STM32H7_QUADSPI_DLR_OFFSET 0x0010
#define STM32H7_QUADSPI_CCR_OFFSET 0x0014
#define STM32H7_QUADSPI_AR_OFFSET  0x0018
#define STM32H7_QUADSPI_DR_OFFSET  0x0020

/* Register bit definitions */

#define QUADSPI_CR_EN             PBL_BIT(0)
#define QUADSPI_CR_ABORT          PBL_BIT(1)
#define QUADSPI_CR_SSHIFT         PBL_BIT(4)
#define QUADSPI_CR_DFM            PBL_BIT(6)
#define QUADSPI_CR_FTHRES_MASK    PBL_GENMASK(12, 8)
#define QUADSPI_CR_PRESCALER_MASK PBL_GENMASK(31, 24)

#define QUADSPI_DCR_CSHT_MASK  PBL_GENMASK(10, 8)
#define QUADSPI_DCR_FSIZE_MASK PBL_GENMASK(20, 16)

#define QUADSPI_SR_TEF         PBL_BIT(0)
#define QUADSPI_SR_TCF         PBL_BIT(1)
#define QUADSPI_SR_FTF         PBL_BIT(2)
#define QUADSPI_SR_BUSY        PBL_BIT(5)
#define QUADSPI_SR_FLEVEL_MASK PBL_GENMASK(13, 8)

#define QUADSPI_FCR_ALL 0x1bU

#define QUADSPI_CCR_INSTRUCTION_MASK PBL_GENMASK(7, 0)
#define QUADSPI_CCR_IMODE_MASK       PBL_GENMASK(9, 8)
#define QUADSPI_CCR_ADMODE_MASK      PBL_GENMASK(11, 10)
#define QUADSPI_CCR_ADSIZE_MASK      PBL_GENMASK(13, 12)
#define QUADSPI_CCR_DCYC_MASK        PBL_GENMASK(22, 18)
#define QUADSPI_CCR_DMODE_MASK       PBL_GENMASK(25, 24)
#define QUADSPI_CCR_FMODE_MASK       PBL_GENMASK(27, 26)
#define QUADSPI_CCR_FMODE_WRITE      0U
#define QUADSPI_CCR_FMODE_READ       1U

#define QUADSPI_DCYC_MAX 31U
