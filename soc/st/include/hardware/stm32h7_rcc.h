#pragma once

#include <pbl/util/bits.h>

/* Register offsets. The enable registers are those of the CPU accessing them. */

#define STM32H7_RCC_CR_OFFSET         0x0000
#define STM32H7_RCC_CFGR_OFFSET       0x0010
#define STM32H7_RCC_D1CFGR_OFFSET     0x0018
#define STM32H7_RCC_D2CFGR_OFFSET     0x001c
#define STM32H7_RCC_D3CFGR_OFFSET     0x0020
#define STM32H7_RCC_PLLCKSELR_OFFSET  0x0028
#define STM32H7_RCC_PLLCFGR_OFFSET    0x002c
#define STM32H7_RCC_PLLDIVR_OFFSET(n) (0x0030 + 0x8 * (n))
#define STM32H7_RCC_D2CCIP2R_OFFSET   0x0054
#define STM32H7_RCC_D3CCIPR_OFFSET    0x0058
#define STM32H7_RCC_BDCR_OFFSET       0x0070
#define STM32H7_RCC_CSR_OFFSET        0x0074
#define STM32H7_RCC_GCR_OFFSET        0x00a0
#define STM32H7_RCC_AHB3ENR_OFFSET    0x00d4
#define STM32H7_RCC_AHB1ENR_OFFSET    0x00d8
#define STM32H7_RCC_AHB2ENR_OFFSET    0x00dc
#define STM32H7_RCC_AHB4ENR_OFFSET    0x00e0
#define STM32H7_RCC_APB1LENR_OFFSET   0x00e8
#define STM32H7_RCC_APB2ENR_OFFSET    0x00f0
#define STM32H7_RCC_APB4ENR_OFFSET    0x00f4
#define STM32H7_RCC_C1_RSR_OFFSET     0x0130

/* Register bit definitions */

#define RCC_GCR_BOOT_C2 PBL_BIT(3)

#define RCC_AHB3ENR_FLASHEN PBL_BIT(8)

#define RCC_CR_HSION       PBL_BIT(0)
#define RCC_CR_HSIRDY      PBL_BIT(2)
#define RCC_CR_HSIDIV_MASK PBL_GENMASK(4, 3)
#define RCC_CR_CSION       PBL_BIT(7)
#define RCC_CR_CSIRDY      PBL_BIT(8)
#define RCC_CR_HSI48ON     PBL_BIT(12)
#define RCC_CR_HSI48RDY    PBL_BIT(13)
#define RCC_CR_HSEON       PBL_BIT(16)
#define RCC_CR_HSERDY      PBL_BIT(17)
#define RCC_CR_PLLON(n)    PBL_BIT(24 + 2 * (n))
#define RCC_CR_PLLRDY(n)   PBL_BIT(25 + 2 * (n))

#define RCC_CFGR_SW_MASK  PBL_GENMASK(2, 0)
#define RCC_CFGR_SWS_MASK PBL_GENMASK(5, 3)
#define RCC_CFGR_SW_HSI   0U
#define RCC_CFGR_SW_CSI   1U
#define RCC_CFGR_SW_HSE   2U
#define RCC_CFGR_SW_PLL1  3U

#define RCC_D1CFGR_HPRE_MASK   PBL_GENMASK(3, 0)
#define RCC_D1CFGR_D1PPRE_MASK PBL_GENMASK(6, 4)
#define RCC_D1CFGR_D1CPRE_MASK PBL_GENMASK(11, 8)

#define RCC_D2CFGR_D2PPRE1_MASK PBL_GENMASK(6, 4)
#define RCC_D2CFGR_D2PPRE2_MASK PBL_GENMASK(10, 8)

#define RCC_D3CFGR_D3PPRE_MASK PBL_GENMASK(6, 4)

#define RCC_PLLCKSELR_PLLSRC_MASK  PBL_GENMASK(1, 0)
#define RCC_PLLCKSELR_PLLSRC_HSI   0U
#define RCC_PLLCKSELR_PLLSRC_CSI   1U
#define RCC_PLLCKSELR_PLLSRC_HSE   2U
#define RCC_PLLCKSELR_DIVM_MASK(n) PBL_GENMASK(9 + 8 * (n), 4 + 8 * (n))

#define RCC_PLLCFGR_FRACEN(n)     PBL_BIT(4 * (n))
#define RCC_PLLCFGR_VCOSEL(n)     PBL_BIT(1 + 4 * (n))
#define RCC_PLLCFGR_RGE_MASK(n)   PBL_GENMASK(3 + 4 * (n), 2 + 4 * (n))
#define RCC_PLLCFGR_RGE_1_2MHZ    0U
#define RCC_PLLCFGR_RGE_2_4MHZ    1U
#define RCC_PLLCFGR_RGE_4_8MHZ    2U
#define RCC_PLLCFGR_RGE_8_16MHZ   3U
#define RCC_PLLCFGR_DIVEN(n, out) PBL_BIT(16 + 3 * (n) + (out))
#define RCC_PLLCFGR_DIVEN_ALL(n)  PBL_GENMASK(18 + 3 * (n), 16 + 3 * (n))

#define RCC_PLLDIVR_N_MASK PBL_GENMASK(8, 0)
#define RCC_PLLDIVR_P_MASK PBL_GENMASK(15, 9)
#define RCC_PLLDIVR_Q_MASK PBL_GENMASK(22, 16)
#define RCC_PLLDIVR_R_MASK PBL_GENMASK(30, 24)

#define RCC_D2CCIP2R_USART234578SEL_MASK PBL_GENMASK(2, 0)
#define RCC_D2CCIP2R_USART16SEL_MASK     PBL_GENMASK(5, 3)
#define RCC_D2CCIP2R_USARTSEL_PCLK       0U
#define RCC_D2CCIP2R_USARTSEL_HSI_KER    3U
#define RCC_D2CCIP2R_USARTSEL_CSI_KER    4U
#define RCC_D2CCIP2R_USARTSEL_LSE        5U
#define RCC_D2CCIP2R_RNGSEL_MASK         PBL_GENMASK(9, 8)
#define RCC_D2CCIP2R_RNGSEL_HSI48        0U
#define RCC_D2CCIP2R_RNGSEL_PLL1_Q       1U
#define RCC_D2CCIP2R_RNGSEL_LSE          2U
#define RCC_D2CCIP2R_RNGSEL_LSI          3U

#define RCC_CSR_LSION  PBL_BIT(0)
#define RCC_CSR_LSIRDY PBL_BIT(1)

#define RCC_RSR_RMVF      PBL_BIT(16)
#define RCC_RSR_BORRSTF   PBL_BIT(21)
#define RCC_RSR_PINRSTF   PBL_BIT(22)
#define RCC_RSR_PORRSTF   PBL_BIT(23)
#define RCC_RSR_SFT1RSTF  PBL_BIT(24)
#define RCC_RSR_IWDG1RSTF PBL_BIT(26)
#define RCC_RSR_WWDG1RSTF PBL_BIT(28)
#define RCC_RSR_LPWR1RSTF PBL_BIT(30)

#define RCC_D2CCIP2R_LPTIM1SEL_MASK PBL_GENMASK(30, 28)
#define RCC_D3CCIPR_LPTIM2SEL_MASK  PBL_GENMASK(12, 10)

/* Kernel clock of the LPTIMs, the same values for each */
#define RCC_LPTIMSEL_PCLK   0U
#define RCC_LPTIMSEL_PLL2_P 1U
#define RCC_LPTIMSEL_PLL3_R 2U
#define RCC_LPTIMSEL_LSE    3U
#define RCC_LPTIMSEL_LSI    4U

#define RCC_BDCR_LSEON  PBL_BIT(0)
#define RCC_BDCR_LSERDY PBL_BIT(1)

/* Bus prescaler fields: 0xxx is 1, 1000 to 1111 are 2 to 512 without 32 (HPRE, D1CPRE) */
#define RCC_AHB_PRE_DIVIDED PBL_BIT(3)
/* 0xx is 1, 100 to 111 are 2 to 16 (PPRE) */
#define RCC_APB_PRE_DIVIDED PBL_BIT(2)

#define STM32H7_HSI_HZ   64000000U
#define STM32H7_CSI_HZ   4000000U
#define STM32H7_HSI48_HZ 48000000U
#define STM32H7_LSI_HZ   32000U
