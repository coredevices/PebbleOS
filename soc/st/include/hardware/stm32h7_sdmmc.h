#pragma once

#include <pbl/util/bits.h>

/* Register offsets */

#define STM32H7_SDMMC_POWER_OFFSET      0x0000
#define STM32H7_SDMMC_CLKCR_OFFSET      0x0004
#define STM32H7_SDMMC_ARGR_OFFSET       0x0008
#define STM32H7_SDMMC_CMDR_OFFSET       0x000c
#define STM32H7_SDMMC_RESPR_OFFSET(n)   (0x0014 + 4U * (n))
#define STM32H7_SDMMC_DTIMER_OFFSET     0x0024
#define STM32H7_SDMMC_DLENR_OFFSET      0x0028
#define STM32H7_SDMMC_DCTRL_OFFSET      0x002c
#define STM32H7_SDMMC_STAR_OFFSET       0x0034
#define STM32H7_SDMMC_ICR_OFFSET        0x0038
#define STM32H7_SDMMC_MASKR_OFFSET      0x003c
#define STM32H7_SDMMC_IDMACTRLR_OFFSET  0x0050
#define STM32H7_SDMMC_IDMABASE0R_OFFSET 0x0058
#define STM32H7_SDMMC_FIFOR_OFFSET      0x0080

/* Register bit definitions */

#define SDMMC_POWER_PWRCTRL_ON 0x3U

#define SDMMC_CLKCR_CLKDIV_MASK PBL_GENMASK(9, 0)
#define SDMMC_CLKCR_WIDBUS_MASK PBL_GENMASK(15, 14)
#define SDMMC_CLKCR_WIDBUS_4    1U
#define SDMMC_CLKCR_NEGEDGE     PBL_BIT(16)
#define SDMMC_CLKCR_HWFC_EN     PBL_BIT(17)

#define SDMMC_CMDR_CMDINDEX_MASK         PBL_GENMASK(5, 0)
#define SDMMC_CMDR_CMDTRANS              PBL_BIT(6)
#define SDMMC_CMDR_CMDSTOP               PBL_BIT(7)
#define SDMMC_CMDR_WAITRESP_MASK         PBL_GENMASK(9, 8)
#define SDMMC_CMDR_WAITRESP_SHORT        1U
#define SDMMC_CMDR_WAITRESP_SHORT_NO_CRC 2U
#define SDMMC_CMDR_WAITRESP_LONG         3U
#define SDMMC_CMDR_CPSMEN                PBL_BIT(12)

#define SDMMC_DCTRL_DTDIR           PBL_BIT(1)
#define SDMMC_DCTRL_DBLOCKSIZE_MASK PBL_GENMASK(7, 4)

#define SDMMC_STAR_CCRCFAIL  PBL_BIT(0)
#define SDMMC_STAR_DCRCFAIL  PBL_BIT(1)
#define SDMMC_STAR_CTIMEOUT  PBL_BIT(2)
#define SDMMC_STAR_DTIMEOUT  PBL_BIT(3)
#define SDMMC_STAR_TXUNDERR  PBL_BIT(4)
#define SDMMC_STAR_RXOVERR   PBL_BIT(5)
#define SDMMC_STAR_CMDREND   PBL_BIT(6)
#define SDMMC_STAR_CMDSENT   PBL_BIT(7)
#define SDMMC_STAR_DATAEND   PBL_BIT(8)
#define SDMMC_STAR_TXFIFOHE  PBL_BIT(14)
#define SDMMC_STAR_RXFIFOHF  PBL_BIT(15)
#define SDMMC_STAR_RXFIFOE   PBL_BIT(19)
#define SDMMC_STAR_BUSYD0    PBL_BIT(20)
#define SDMMC_STAR_BUSYD0END PBL_BIT(21)
#define SDMMC_STAR_IDMATE    PBL_BIT(27)

#define SDMMC_IDMACTRLR_IDMAEN PBL_BIT(0)

/* The static flags ICR clears */
#define SDMMC_ICR_ALL 0x1fe00fffU

/* Words in half the FIFO */
#define SDMMC_FIFO_HALF_WORDS 8U
