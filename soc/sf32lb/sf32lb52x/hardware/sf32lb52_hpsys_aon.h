#define HPSYS_AON_ACR_HXT48_RDY PBL_BIT(31)

#define HPSYS_AON_WER_GPIO1     PBL_BIT(1)
#define HPSYS_AON_WER_LPTIM1    PBL_BIT(2)
#define HPSYS_AON_WER_LP2HP_REQ PBL_BIT(6)
#define HPSYS_AON_WER_LP2HP_IRQ PBL_BIT(7)

#define HPSYS_AON_WSR_PIN_ALL PBL_GENMASK(28, 8)

/* Wakeup pin n is pad PA24 + n */
