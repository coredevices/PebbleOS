/* Register offsets */

#define SF32LB52_HPSYS_AON_PMR_OFFSET   0x0000
#define SF32LB52_HPSYS_AON_CR1_OFFSET   0x0004
#define SF32LB52_HPSYS_AON_ACR_OFFSET   0x0010
#define SF32LB52_HPSYS_AON_WER_OFFSET   0x0020
#define SF32LB52_HPSYS_AON_WSR_OFFSET   0x0024
#define SF32LB52_HPSYS_AON_WCR_OFFSET   0x0028
#define SF32LB52_HPSYS_AON_ISSR_OFFSET  0x002C
#define SF32LB52_HPSYS_AON_ANACR_OFFSET 0x0030
#define SF32LB52_HPSYS_AON_GTIMR_OFFSET 0x0034

/* Register bit definitions */

#define HPSYS_AON_PMR_MODE_MASK       PBL_GENMASK(1, 0)
#define HPSYS_AON_PMR_MODE_DEEP_SLEEP 2U

#define HPSYS_AON_CR1_PINOUT_SEL0_MASK      PBL_GENMASK(27, 25)
#define HPSYS_AON_CR1_PINOUT_SEL1_MASK      PBL_GENMASK(30, 28)
#define HPSYS_AON_CR1_PINOUT_SEL_LPTIM1_OUT 2U
#define HPSYS_AON_CR1_PINOUT_SEL_LPTIM2_OUT 3U
