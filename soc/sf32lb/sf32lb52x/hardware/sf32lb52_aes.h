#pragma once

#include <pbl/util/bits.h>

/* Register offsets */

#define SF32LB52_AES_COMMAND_OFFSET        0x0000
#define SF32LB52_AES_STATUS_OFFSET         0x0004
#define SF32LB52_AES_IRQ_OFFSET            0x0008
#define SF32LB52_AES_SETTING_OFFSET        0x000C
#define SF32LB52_AES_AES_SETTING_OFFSET    0x0010
#define SF32LB52_AES_DMA_IN_OFFSET         0x0014
#define SF32LB52_AES_DMA_OUT_OFFSET        0x0018
#define SF32LB52_AES_DMA_DATA_OFFSET       0x001C
#define SF32LB52_AES_EXT_KEY_OFFSET(n)     (0x0030 + 4 * (n))
#define SF32LB52_AES_HASH_SETTING_OFFSET   0x0050
#define SF32LB52_AES_HASH_DMA_IN_OFFSET    0x0054
#define SF32LB52_AES_HASH_DMA_DATA_OFFSET  0x0058
#define SF32LB52_AES_HASH_IV_OFFSET(n)     (0x005C + 4 * (n))
#define SF32LB52_AES_HASH_RESULT_OFFSET(n) (0x007C + 4 * (n))

/* Register bit definitions */

#define AES_COMMAND_START      PBL_BIT(0)
#define AES_COMMAND_AES_RESET  PBL_BIT(1)
#define AES_COMMAND_HASH_START PBL_BIT(2)
#define AES_COMMAND_HASH_RESET PBL_BIT(3)

#define AES_STATUS_BUSY      PBL_BIT(0)
#define AES_STATUS_HASH_BUSY PBL_BIT(2)

#define AES_IRQ_BUS_ERR      PBL_BIT(1)
#define AES_IRQ_SETUP_ERR    PBL_BIT(2)
#define AES_IRQ_HASH_BUS_ERR PBL_BIT(4)
#define AES_IRQ_HASH_PAD_ERR PBL_BIT(5)

#define AES_AES_SETTING_MODE_MASK   PBL_GENMASK(2, 0)
#define AES_AES_SETTING_MODE_ECB    0U
#define AES_AES_SETTING_LENGTH_MASK PBL_GENMASK(4, 3)
#define AES_AES_SETTING_LENGTH_128  0U
#define AES_AES_SETTING_LENGTH_192  1U
#define AES_AES_SETTING_LENGTH_256  2U
#define AES_AES_SETTING_ENCRYPT     PBL_BIT(7)

#define AES_HASH_SETTING_MODE_MASK   PBL_GENMASK(2, 0)
#define AES_HASH_SETTING_MODE_SHA256 2U
#define AES_HASH_SETTING_IV_SEL      PBL_BIT(5)
#define AES_HASH_SETTING_IV_LOAD     PBL_BIT(7)
