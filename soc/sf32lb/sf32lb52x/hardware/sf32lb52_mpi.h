#pragma once

#include <pbl/util/bits.h>

#include <hardware/sf32lb52_memorymap.h>

/* Register offsets */

#define SF32LB52_MPI_CR_OFFSET     0x0000
#define SF32LB52_MPI_DR_OFFSET     0x0004
#define SF32LB52_MPI_DCR_OFFSET    0x0008
#define SF32LB52_MPI_PSCLR_OFFSET  0x000c
#define SF32LB52_MPI_SR_OFFSET     0x0010
#define SF32LB52_MPI_SCR_OFFSET    0x0014
#define SF32LB52_MPI_CMDR1_OFFSET  0x0018
#define SF32LB52_MPI_AR1_OFFSET    0x001c
#define SF32LB52_MPI_ABR1_OFFSET   0x0020
#define SF32LB52_MPI_DLR1_OFFSET   0x0024
#define SF32LB52_MPI_CCR1_OFFSET   0x0028
#define SF32LB52_MPI_HCMDR_OFFSET  0x0040
#define SF32LB52_MPI_HRABR_OFFSET  0x0044
#define SF32LB52_MPI_HRCCR_OFFSET  0x0048
#define SF32LB52_MPI_FIFOCR_OFFSET 0x0054
#define SF32LB52_MPI_MISCR_OFFSET  0x0058
#define SF32LB52_MPI_CIR_OFFSET    0x0078
#define SF32LB52_MPI_TIMR_OFFSET   0x0084

/* Register bit definitions */

#define MPI_CR_EN   PBL_BIT(0)
#define MPI_CR_DMAE PBL_BIT(5)
#define MPI_CR_DFM  PBL_BIT(24)

#define MPI_SR_TCF  PBL_BIT(0)
#define MPI_SR_BUSY PBL_BIT(31)

#define MPI_SCR_TCFC PBL_BIT(0)

#define MPI_CMDR_CMD_MASK PBL_GENMASK(7, 0)

#define MPI_DLR_DLEN_MASK PBL_GENMASK(19, 0)

/* CCR1 and HRCCR share their layout */
#define MPI_CCR_IMODE_MASK  PBL_GENMASK(2, 0)
#define MPI_CCR_ADMODE_MASK PBL_GENMASK(5, 3)
#define MPI_CCR_ADSIZE_MASK PBL_GENMASK(7, 6)
#define MPI_CCR_ABMODE_MASK PBL_GENMASK(10, 8)
#define MPI_CCR_ABSIZE_MASK PBL_GENMASK(12, 11)
#define MPI_CCR_DCYC_MASK   PBL_GENMASK(17, 13)
#define MPI_CCR_DMODE_MASK  PBL_GENMASK(20, 18)
#define MPI_CCR_FMODE_WRITE PBL_BIT(21)

#define MPI_CCR_MODE_NONE   0U
#define MPI_CCR_MODE_SINGLE 1U
#define MPI_CCR_MODE_DUAL   2U
#define MPI_CCR_MODE_QUAD   3U

#define MPI_HCMDR_RCMD_MASK PBL_GENMASK(7, 0)

#define MPI_FIFOCR_RXCLR        PBL_BIT(0)
#define MPI_FIFOCR_TXCLR        PBL_BIT(8)
