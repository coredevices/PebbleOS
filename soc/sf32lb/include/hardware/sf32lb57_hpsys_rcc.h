#pragma once

#include <pbl/util/bits.h>

/*
 * The SF32LB57 HPSYS RCC is the SF32LB52 one (sf32lb52_hpsys_rcc.h) without CSR.SEL_SYS_LP,
 * plus the gates of its own blocks and these fields.
 */

#define HPSYS_RCC_CSR_SEL_MPI3_MASK PBL_GENMASK(9, 8)

#define SF32LB57_HPSYS_RCC_RC10CAL1_OFFSET 0x0050
#define SF32LB57_HPSYS_RCC_RC10CAL2_OFFSET 0x0054

#define HPSYS_RCC_RC10CAL1_CAL_LENGTH_MASK PBL_GENMASK(15, 0)
#define HPSYS_RCC_RC10CAL1_CAL_AUTO        PBL_BIT(16)
#define HPSYS_RCC_RC10CAL1_CAL_START       PBL_BIT(17)
#define HPSYS_RCC_RC10CAL1_CAL_STOP        PBL_BIT(18)
#define HPSYS_RCC_RC10CAL1_CAL_SEL         PBL_BIT(19)
#define HPSYS_RCC_RC10CAL1_CON_NUM_MASK    PBL_GENMASK(29, 20)
#define HPSYS_RCC_RC10CAL1_CON_MODE        PBL_BIT(30)

#define HPSYS_RCC_RC10CAL2_CAL_RSLT_MASK PBL_GENMASK(30, 0)
#define HPSYS_RCC_RC10CAL2_CAL_DONE      PBL_BIT(31)

#define SF32LB57_HPSYS_RCC_DLLCR_IN_DIV2_EN  PBL_BIT(13)
#define SF32LB57_HPSYS_RCC_DLLCR_OUT_DIV2_EN PBL_BIT(14)
