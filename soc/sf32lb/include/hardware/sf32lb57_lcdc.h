/*
 * The SF32LB57 LCDC is the SF32LB52 one with a second layer right after the first, which moves the
 * registers that follow, wider coordinates and fields, and a divided interface clock.
 */

/* Register offsets */

#define SF32LB57_LCDC_COMMAND_OFFSET         0x0000
#define SF32LB57_LCDC_STATUS_OFFSET          0x0004
#define SF32LB57_LCDC_IRQ_OFFSET             0x0008
#define SF32LB57_LCDC_SETTING_OFFSET         0x000c
#define SF32LB57_LCDC_CANVAS_TL_POS_OFFSET   0x0010
#define SF32LB57_LCDC_CANVAS_BR_POS_OFFSET   0x0014
#define SF32LB57_LCDC_CANVAS_BG_OFFSET       0x0018
#define SF32LB57_LCDC_LAYER0_CONFIG_OFFSET   0x001c
#define SF32LB57_LCDC_LAYER0_TL_POS_OFFSET   0x0020
#define SF32LB57_LCDC_LAYER0_BR_POS_OFFSET   0x0024
#define SF32LB57_LCDC_LAYER0_FILTER_OFFSET   0x0028
#define SF32LB57_LCDC_LAYER0_SRC_OFFSET      0x002c
#define SF32LB57_LCDC_LAYER0_FILL_OFFSET     0x0030
#define SF32LB57_LCDC_LAYER1_CONFIG_OFFSET   0x0040
#define SF32LB57_LCDC_LCD_CONF_OFFSET        0x0070
#define SF32LB57_LCDC_LCD_IF_CONF_OFFSET     0x0074
#define SF32LB57_LCDC_LCD_SINGLE_OFFSET      0x0080
#define SF32LB57_LCDC_LCD_WR_OFFSET          0x0084
#define SF32LB57_LCDC_LCD_RD_OFFSET          0x0088
#define SF32LB57_LCDC_SPI_IF_CONF_OFFSET     0x008c
#define SF32LB57_LCDC_SPI_IF_CONF_EXT_OFFSET 0x0090
#define SF32LB57_LCDC_TE_CONF_OFFSET         0x0094

