#pragma once

#include <pbl/util/bits.h>

/* Register offsets */

#define SF32LB57_GPADC_CFG_REG1_OFFSET  0x0000
#define SF32LB57_GPADC_CFG_REG2_OFFSET  0x0004
#define SF32LB57_GPADC_SLOT_OFFSET(n)   (0x0008 + ((n) * 4))
#define SF32LB57_GPADC_RDATA_OFFSET(n)  (0x0038 + ((n) * 4))
#define SF32LB57_GPADC_CTRL_REG_OFFSET  0x0054
#define SF32LB57_GPADC_CTRL_REG2_OFFSET 0x0058
#define SF32LB57_GPADC_IRQ_OFFSET       0x0060

/* Register bit definitions */

#define GPADC_CFG_REG1_EN_V18    PBL_BIT(6)
#define GPADC_CFG_REG1_SE        PBL_BIT(7)
#define GPADC_CFG_REG1_MUTE      PBL_BIT(8)
#define GPADC_CFG_REG1_LDOREF_EN PBL_BIT(21)
#define GPADC_CFG_REG1_VSP_MASK  PBL_GENMASK(23, 22)

#define GPADC_CFG_REG2_LDO_SW_EN PBL_BIT(0)

#define GPADC_SLOT_EN         PBL_BIT(0)
#define GPADC_SLOT_PCHNL_MASK PBL_GENMASK(11, 8)
#define GPADC_SLOT_NCHNL_MASK PBL_GENMASK(15, 12)
#define GPADC_SLOT_ACC_MASK   PBL_GENMASK(17, 16)

/* Two slots per RDATA register, the even one in the low half */
#define GPADC_RDATA_EVEN_MASK PBL_GENMASK(15, 0)
#define GPADC_RDATA_ODD_MASK  PBL_GENMASK(31, 16)

#define GPADC_CTRL_REG_ADC_START      PBL_BIT(1)
#define GPADC_CTRL_REG_INIT_TIME_MASK PBL_GENMASK(7, 4)
#define GPADC_CTRL_REG_GPIO_TRIG_EN   PBL_BIT(9)
#define GPADC_CTRL_REG_TIMER_TRIG_EN  PBL_BIT(10)
#define GPADC_CTRL_REG_FRC_EN_ADC     PBL_BIT(12)
#define GPADC_CTRL_REG_SAMP_DLY_MASK  PBL_GENMASK(21, 18)
#define GPADC_CTRL_REG_UNSIGNED_RSLT  PBL_BIT(29)

#define GPADC_CTRL_REG2_SAMP_WIDTH_MASK PBL_GENMASK(23, 0)
#define GPADC_CTRL_REG2_CONV_WIDTH_MASK PBL_GENMASK(31, 24)

#define GPADC_IRQ_ICR  PBL_BIT(0)
#define GPADC_IRQ_IMR  PBL_BIT(1)
#define GPADC_IRQ_IRSR PBL_BIT(2)
