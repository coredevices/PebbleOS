uint8_t pbl_utf8_decode(uint8_t *state, uint32_t *codepoint, uint8_t byte) {
  uint8_t type = s_utf8d[byte];

  *codepoint =
      (*state != PBL_UTF8_ACCEPT) ? (byte & 0x3fu) | (*codepoint << 6) : (0xffu >> type) & byte;

  *state = s_utf8d[256 + *state + type];
  return *state;
}
