"""Generate the filter tables of lib/pdm.

The first stage is a fifth-order sinc filter decimating by 8, applied a byte
of PDM samples at a time through one lookup table per byte of its span. The
second stage is an equiripple low-pass FIR decimating by 8 or 16 down to the
output rate, flat to 0.4 times the output rate and stopping from 0.6 times
it, so that nothing aliases into the passband.

Usage: pdm_tables.py lib/pdm/pdm_tables.h
"""

import argparse

import numpy as np
from scipy import signal

SINC_ORDER = 5
SINC_DECIMATION = 8
# Taps of the second stage for each of its decimations
FIR_TAPS = {8: 128, 16: 256}
FIR_STOP_WEIGHT = 30


def sinc_kernel():
    kernel = np.ones(1)
    for _ in range(SINC_ORDER):
        kernel = np.convolve(kernel, np.ones(SINC_DECIMATION))
    return kernel.astype(int)


def sinc_tables():
    """Contribution of each byte of the span, bit i being the sample i before the newest."""
    kernel = sinc_kernel()
    span = -(-len(kernel) // 8)
    kernel = np.concatenate([kernel, np.zeros(span * 8 - len(kernel), dtype=int)])
    tables = []
    for byte in range(span):
        taps = kernel[byte * 8 : byte * 8 + 8]
        tables.append(
            [
                int(sum(t if (v >> i) & 1 else -t for i, t in enumerate(taps)))
                for v in range(256)
            ]
        )
    return tables


def fir(decimation):
    taps = signal.remez(
        FIR_TAPS[decimation],
        [0, 0.4, 0.6, decimation / 2],
        [1, 0],
        weight=[1, FIR_STOP_WEIGHT],
        fs=decimation,
        maxiter=200,
    )
    taps /= taps.sum()
    shift = 15
    while np.abs(taps).max() * (1 << (shift + 1)) < 32767:
        shift += 1
    return np.round(taps * (1 << shift)).astype(int), shift


def c_array(name, ctype, values, per_line=12):
    lines = [f"static const {ctype} {name}[] = {{"]
    for i in range(0, len(values), per_line):
        lines.append("  " + ", ".join(str(v) for v in values[i : i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output")
    args = parser.parse_args()

    tables = sinc_tables()
    out = [
        "/* SPDX-FileCopyrightText: 2026 Core Devices LLC */",
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "",
        "/* Generated by tools/pdm/pdm_tables.py, do not edit */",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define SINC_BYTES {len(tables)}",
        f"#define SINC_GAIN  {SINC_DECIMATION**SINC_ORDER}",
        "",
        "static const int16_t s_sinc[SINC_BYTES][256] = {",
    ]
    for table in tables:
        out.append("  {")
        for i in range(0, 256, 12):
            out.append("    " + ", ".join(str(v) for v in table[i : i + 12]) + ",")
        out.append("  },")
    out.append("};")
    for decimation in sorted(FIR_TAPS):
        taps, shift = fir(decimation)
        out += [
            "",
            f"#define FIR{decimation}_SHIFT {shift}",
            "",
            c_array(f"s_fir{decimation}", "int16_t", list(taps)),
        ]
    with open(args.output, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
