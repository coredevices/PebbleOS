// FIPS 197 Appendix B
void test_aes__cipher_example(void) {
  static const uint8_t key[] = {
    0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c,
  };
  static const uint8_t plain[] = {
    0x32, 0x43, 0xf6, 0xa8, 0x88, 0x5a, 0x30, 0x8d, 0x31, 0x31, 0x98, 0xa2, 0xe0, 0x37, 0x07, 0x34,
  };
  static const uint8_t expected[] = {
    0x39, 0x25, 0x84, 0x1d, 0x02, 0xdc, 0x09, 0xfb, 0xdc, 0x11, 0x85, 0x97, 0x19, 0x6a, 0x0b, 0x32,
  };
  struct pbl_aes_ctx ctx;
  uint8_t block[PBL_AES_BLOCK_SIZE];

  cl_assert_equal_i(pbl_aes_expandkey(&ctx, key, sizeof(key)), 0);
  pbl_aes_encrypt(&ctx, block, plain);
  cl_assert_equal_m(block, expected, sizeof(expected));
  pbl_aes_decrypt(&ctx, block, expected);
  cl_assert_equal_m(block, plain, sizeof(plain));
}

void test_aes__invalid_key_size(void) {
  struct pbl_aes_ctx ctx;

  cl_assert_equal_i(pbl_aes_expandkey(&ctx, s_key, 0), -EINVAL);
  cl_assert_equal_i(pbl_aes_expandkey(&ctx, s_key, 15), -EINVAL);
  cl_assert_equal_i(pbl_aes_expandkey(&ctx, s_key, 20), -EINVAL);
  cl_assert_equal_i(pbl_aes_expandkey(&ctx, s_key, 33), -EINVAL);
}

