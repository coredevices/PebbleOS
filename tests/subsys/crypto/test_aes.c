static const uint8_t s_key[32] = {
  0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
  0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
};

static const uint8_t s_plain[PBL_AES_BLOCK_SIZE] = {
  0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
};

static void prv_check(size_t key_len, const uint8_t expected[PBL_AES_BLOCK_SIZE]) {
  struct pbl_aes_ctx ctx;
  uint8_t block[PBL_AES_BLOCK_SIZE];

  cl_assert_equal_i(pbl_aes_expandkey(&ctx, s_key, key_len), 0);

  pbl_aes_encrypt(&ctx, block, s_plain);
  cl_assert_equal_m(block, expected, PBL_AES_BLOCK_SIZE);

  pbl_aes_decrypt(&ctx, block, block);
  cl_assert_equal_m(block, s_plain, PBL_AES_BLOCK_SIZE);
}

